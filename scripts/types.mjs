// TypeScript types of the data the pages read, generated from its JSON Schemas into types/, for the
// type check of assets/*.js (jsconfig.json). The fetcher's schemas are read from schema/ (linked to the data,
// README "Running locally"), the ski tiles' from scripts/ski-tile.schema.json.
//
//   node scripts/types.mjs           write types/*.d.ts
//   node scripts/types.mjs --check   fail when they differ from the schemas (skipped without schema/)

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { compile } from "json-schema-to-typescript";

const SCHEMAS = {
  "schema/index.schema.json": "types/index.d.ts",
  "schema/resort.schema.json": "types/resort.d.ts",
  "schema/history.schema.json": "types/history.d.ts",
  "schema/stats.schema.json": "types/stats.d.ts",
  "schema/resort-details.schema.json": "types/resort-details.d.ts",
  "scripts/ski-tile.schema.json": "types/ski-tile.d.ts",
};
const BANNER = "// Generated by scripts/types.mjs from {schema}: don't edit, run `npm run types`.";

const check = process.argv.includes("--check");
if (check && !existsSync("schema/index.schema.json")) {
  console.log("types: no schema/ here, so the generated types are not compared with it");
  process.exit(0);
}
let stale = 0;
for (const [schema, out] of Object.entries(SCHEMAS)) {
  const json = JSON.parse(readFileSync(schema, "utf8"));
  const types = await compile(json, json.title, {
    cwd: dirname(schema),
    bannerComment: BANNER.replace("{schema}", schema),
    additionalProperties: false,
    format: false,
  });
  const old = existsSync(out) ? readFileSync(out, "utf8") : null;
  if (types === old) continue;
  if (check) {
    console.error(`${out} differs from ${schema}: run npm run types`);
    stale++;
  } else {
    writeFileSync(out, types);
    console.log(`wrote ${out}`);
  }
}
process.exit(stale ? 1 : 0);
